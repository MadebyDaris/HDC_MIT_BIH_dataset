"""
export_prototypes_c.py

Quantizes the Centroid HDC model to the binary/bipolar domain and emits a C
header (hyperdim_model.h) that the hyperdim-rocc bare-metal tests compile
directly. Also prints the Hamming accuracy of the *quantized* model — that
is the number the hardware will reproduce, so check it before going to RTL
simulation.

Why bipolar?
  The RoCC accelerator computes Hamming distance on packed bits. For bipolar
  vectors a, b in {-1,+1}^D:  dot(a,b) = D - 2 * hamming(a,b),  so argmin
  Hamming == argmax dot-product. The class_hdc_impl.py benchmark showed
  Hamming at ~7.7% because the Centroid prototypes are real-valued and were
  binarized only at inference time. Training in the bipolar domain (quantize
  samples -> bundle -> majority-vote prototypes) keeps Hamming meaningful.

Usage:
  python export_prototypes_c.py [--pt hdc_dataset.pt] \
                                [--out hyperdim_model.h] [--num-queries 8]

The generated header is meant for hyperdim-rocc/sw/tests. Remember to build
the SoC with enough query-buffer space, e.g. D=10000 -> 157 words:
  new hyperdim.WithHyperDimRoCC(HyperDimParams(vectorBits = 10048))
"""

import argparse

import numpy as np
import torch
from torchhd import models

CLASS_NAMES = ["Normal", "Supraventricular", "Ventricular", "Fusion", "Unknown"]


def bipolarize(t: torch.Tensor) -> torch.Tensor:
    """Map to {-1, +1}; exact zeros (majority ties) resolve to +1."""
    b = torch.sign(t.float())
    b[b == 0] = 1.0
    return b


def train_bipolar_centroid(samples: torch.Tensor, labels: torch.Tensor,
                           dimensions: int, num_classes: int = 5) -> torch.Tensor:
    """Centroid bundling on bipolar samples, then majority -> bipolar prototypes."""
    bin_samples = bipolarize(samples)
    model = models.Centroid(dimensions, num_classes)
    model.add(bin_samples, labels)
    return bipolarize(model.weight.data)


def hamming_accuracy(samples_b: torch.Tensor, labels: torch.Tensor,
                     protos_b: torch.Tensor) -> float:
    mismatches = (samples_b.unsqueeze(1) != protos_b.unsqueeze(0)).sum(dim=2)
    preds = mismatches.argmin(dim=1)
    return (preds == labels).float().mean().item()


def pack_words(bits: torch.Tensor) -> np.ndarray:
    """(R, D) bipolar/{0,1} -> (R, ceil(D/64)) uint64.

    Dimension k lands in bit (k % 64) of word (k // 64) — little-endian
    packing, matching how the RISC-V target loads uint64 words.
    """
    b = (bits > 0).cpu().numpy().astype(np.uint8)
    R, D = b.shape
    W = (D + 63) // 64
    pad = W * 64 - D
    if pad:
        b = np.concatenate([b, np.zeros((R, pad), dtype=np.uint8)], axis=1)
    packed = np.ascontiguousarray(np.packbits(b, axis=1, bitorder="little"))
    return packed.view("<u8").reshape(R, W)


def _fmt_matrix(words: np.ndarray) -> str:
    return ",\n".join(
        "    { " + ", ".join(f"0x{w:016X}ULL" for w in row) + " }" for row in words
    )


def emit_header(path: str, protos_b: torch.Tensor, queries_b: torch.Tensor,
                query_labels: torch.Tensor, dimensions: int):
    C = protos_b.shape[0]
    N = queries_b.shape[0]
    W = (dimensions + 63) // 64

    proto_words = pack_words(protos_b)
    query_words = pack_words(queries_b)
    labels_np = query_labels.cpu().numpy().astype(np.uint8)

    with open(path, "w") as f:
        f.write(f"""/* Auto-generated by export_prototypes_c.py -- do not edit.
 *
 * Bipolar-quantized Centroid model for the hyperdim-rocc accelerator.
 * Bit packing: dimension k -> bit (k % 64) of word (k // 64), little-endian.
 */
#ifndef HYPERDIM_MODEL_H
#define HYPERDIM_MODEL_H

#include <stdint.h>

#define HYPERDIM_DIMENSIONS   {dimensions}
#define HYPERDIM_NUM_WORDS    {W}
#define HYPERDIM_NUM_CLASSES  {C}
#define HYPERDIM_NUM_QUERIES  {N}

static const uint64_t CLASS_HV[HYPERDIM_NUM_CLASSES][HYPERDIM_NUM_WORDS] = {{
{_fmt_matrix(proto_words)}
}};

static const uint64_t TEST_QUERY[HYPERDIM_NUM_QUERIES][HYPERDIM_NUM_WORDS] = {{
{_fmt_matrix(query_words)}
}};

static const uint8_t TEST_LABEL[HYPERDIM_NUM_QUERIES] = {{
    {", ".join(str(int(x)) for x in labels_np)}
}};

#endif /* HYPERDIM_MODEL_H */
""")
    print(f"Wrote {path}: {C} classes x {W} words ({W*64} bits padded from D={dimensions}), "
          f"{N} test queries")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--pt", default="hdc_dataset.pt")
    ap.add_argument("--out", default="hyperdim_model.h")
    ap.add_argument("--num-queries", type=int, default=8)
    args = ap.parse_args()

    print(f"Loading {args.pt}...")
    data = torch.load(args.pt, weights_only=False)
    samples, labels, dimensions = data["samples"], data["labels"], data["dimensions"]
    num_classes = int(labels.max().item()) + 1
    print(f"  {len(samples)} samples, {dimensions} dims, {num_classes} classes")

    # Same reproducible 80/20 split as class_hdc_impl.py
    torch.manual_seed(42)
    dataset = torch.utils.data.TensorDataset(samples, labels)
    n_train = int(0.8 * len(dataset))
    train_ds, test_ds = torch.utils.data.random_split(dataset, [n_train, len(dataset) - n_train])

    print("Training Centroid in the bipolar domain...")
    protos_b = train_bipolar_centroid(samples[train_ds.indices], labels[train_ds.indices],
                                      dimensions, num_classes)

    test_b = bipolarize(samples[test_ds.indices])
    acc = hamming_accuracy(test_b, labels[test_ds.indices], protos_b)
    print(f"\n*** Quantized bipolar Hamming accuracy: {acc*100:.2f}% ***")
    print("(This is the accuracy the RoCC hardware will reproduce.)\n")

    n_q = min(args.num_queries, len(test_ds.indices))
    emit_header(args.out, protos_b, test_b[:n_q], labels[test_ds.indices][:n_q], dimensions)


if __name__ == "__main__":
    main()
